#!/usr/bin/env bash
# dev.sh — try the installer on this machine without pushing or releasing anything. Needs rootless podman and a
# Wayland desktop. Run it from the main checkout (it looks for ../bootc-installer, ../fisherman and ../pkgbuilds).
#
#   image/dev.sh run [--nocheck|--nobuild]   (--nobuild reuses .dev/pkgs) build both packages from the LOCAL checkouts (working trees, uncommitted edits
#                                      included), then start the installer as the ISO does (sway and squeekboard), nested in a window
#   image/dev.sh packages [--nocheck]  only build them, into .dev/pkgs (for: sudo LOCAL_PKGS=$PWD/.dev/pkgs image/build.sh)
#   image/dev.sh shell                 a shell in the dev container with the local packages installed
#   image/dev.sh setup                 (re)build the dev image
#
# The installer lists this machine's disks (it reads /sys) but cannot write to them, two ways over: the container is
# rootless and gets no device files, and BOOTC_DEMO=1 makes "Install" replay a fake transcript instead of starting
# fisherman. Never add --privileged, --device or -v /dev to this script. The log goes to
# probe-logs/dev-run.log and .dev/home/.cache/bootc-installer/ (the installer's own debug log).
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
repo=$(dirname "$here")
dev="$repo/.dev"
pkgs="$dev/pkgs"
img=localhost/boppos-installer-dev
siblings=$(dirname "$repo")
installer_src="${INSTALLER_SRC:-$siblings/bootc-installer}"
fisherman_src="${FISHERMAN_SRC:-$siblings/fisherman}"
tools_src="${BOPPOS_TOOLS_SRC:-$siblings/boppos-tools}"   # the BoppOS icons (the ISO gets them from boppos-artwork)
pkgbuilds_src="${PKGBUILDS_SRC:-$siblings/pkgbuilds}"

cmd="${1:-run}"
[ $# -gt 0 ] && shift
makepkg_flags="-s"
nobuild=0
for a in "$@"; do
    case "$a" in
        --nocheck) makepkg_flags="$makepkg_flags --nocheck" ;;
        --nobuild) nobuild=1 ;;   # run: reuse the packages already in .dev/pkgs
        *) echo "unknown option: $a"; exit 2 ;;
    esac
done

setup() {
    podman build -t "$img" -f "$here/dev/Containerfile" "$here/dev"
}

ensure_image() {
    podman image exists "$img" || setup
}

# Copy a checkout's files (tracked and untracked, not ignored) into dir, skipping the fisherman submodule path.
snapshot() {  # snapshot <checkout> <dir>
    mkdir -p "$2"
    git -C "$1" ls-files -z -co --exclude-standard --deduplicate | grep -zvx fisherman |
        tar -C "$1" --null -T - --ignore-failed-read -cf - | tar -C "$2" -xf -
}

build_packages() {
    for d in "$installer_src" "$fisherman_src"; do
        [ -d "$d/.git" ] || [ -f "$d/.git" ] || { echo "not a git checkout: $d"; exit 2; }
    done
    [ -d "$pkgbuilds_src/.git" ] || [ -f "$pkgbuilds_src/.git" ] || { echo "not a git checkout: $pkgbuilds_src"; exit 2; }
    ensure_image
    local build="$dev/build"
    rm -rf "$build" "$dev/src" "$pkgs"
    mkdir -p "$build" "$dev/src" "$pkgs"

    snapshot "$installer_src" "$dev/src/bootc-installer-local"
    mkdir -p "$dev/src/bootc-installer-local/fisherman"   # the PKGBUILD's prepare() replaces it with fisherman
    snapshot "$fisherman_src" "$dev/src/fisherman-local"
    tar -C "$dev/src" -czf "$build/bootc-installer-local.tar.gz" bootc-installer-local
    tar -C "$dev/src" -czf "$build/fisherman-local.tar.gz" fisherman-local

    # The package recipe is the one in the repository (origin/main), so the dev build packages things the same way.
    git -C "$pkgbuilds_src" fetch -q origin main 2>/dev/null || true
    git -C "$pkgbuilds_src" show origin/main:packages/boppos-bootc-installer/PKGBUILD >"$build/PKGBUILD.real"
    cat >"$build/PKGBUILD" <<'EOF'
# Generated by image/dev.sh: the repository's PKGBUILD, built from local source tarballs.
. ./PKGBUILD.real
pkgrel=99
_commit=local
_fishcommit=local
source=(bootc-installer-local.tar.gz fisherman-local.tar.gz)
sha256sums=(SKIP SKIP)
options=('!debug')
EOF

    # shellcheck disable=SC2016  # expanded inside the container
    podman run --rm --security-opt label=disable -e MAKEPKG_FLAGS="$makepkg_flags" \
        -v "$build:/in:ro" -v "$pkgs:/out" "$img" bash -euo pipefail -c '
        cp -r /in /home/builder/pkg
        chown -R builder:builder /home/builder/pkg
        cd /home/builder/pkg
        sudo -u builder makepkg --noconfirm -f $MAKEPKG_FLAGS
        cp ./*.pkg.tar.zst /out/'
    echo "built: $(find "$pkgs" -name '*.pkg.tar.zst' -printf '%f ')"
}

# Run something in the dev container with the local packages installed and this desktop's Wayland socket.
in_container() {  # in_container <podman flags> -- <command...>
    local flags=()
    while [ "$1" != -- ]; do flags+=("$1"); shift; done
    shift
    local sock="${XDG_RUNTIME_DIR:?no XDG_RUNTIME_DIR}/${WAYLAND_DISPLAY:?no WAYLAND_DISPLAY}"
    [ -S "$sock" ] || { echo "no Wayland socket at $sock"; exit 2; }
    compgen -G "$pkgs/*.pkg.tar.zst" >/dev/null || { echo "no packages in $pkgs; run: $0 packages"; exit 2; }
    mkdir -p "$dev/home" "$repo/probe-logs"
    # The BoppOS icon at the path branding.json names, from the local boppos-tools checkout.
    local icon_mount=()
    local icon=artwork/icons/hicolor/512x512/apps/boppos-icon.png
    if [ -f "$tools_src/$icon" ]; then
        icon_mount=(-v "$tools_src/$icon:/usr/share/icons/hicolor/512x512/apps/boppos-icon.png:ro")
    else
        echo "note: $tools_src/$icon not found; the installer will show no BoppOS icon"
    fi
    # The desktop's socket gets its own name: cage creates a socket of its own, and takes wayland-0 first.
    # unmask=/sys/firmware: podman hides it by default, and the installer refuses to start without /sys/firmware/efi
    # ("It did not start in UEFI mode"). Read-only sysfs; a normal user cannot write EFI variables.
    # shellcheck disable=SC2016  # expanded inside the container
    podman run --rm --security-opt label=disable --security-opt unmask=/sys/firmware "${flags[@]}" \
        -v "$pkgs:/pkgs:ro" \
        -v "$here/airootfs/etc/bootc-installer:/etc/bootc-installer:ro" \
        -v "$here/airootfs/etc/boppos-installer:/etc/boppos-installer:ro" \
        -v "$dev/home:/root" \
        "${icon_mount[@]}" \
        -v "$sock:/tmp/xdg/host-0" \
        -e XDG_RUNTIME_DIR=/tmp/xdg -e WAYLAND_DISPLAY=host-0 \
        -e WLR_RENDERER=pixman -e GSK_RENDERER=cairo \
        -e BOOTC_DEMO=1 -e VANILLA_NO_APPLY_XKB=1 \
        "$img" bash -c '
            pacman -U --noconfirm --needed /pkgs/*.pkg.tar.zst >/tmp/pacman.log 2>&1
            command -v bootc-installer >/dev/null || { tail -n 20 /tmp/pacman.log; exit 1; }
            glib-compile-schemas /usr/share/glib-2.0/schemas
            gtk4-update-icon-cache -qtf /usr/share/icons/hicolor
            chmod 700 /tmp/xdg
            exec "$@"' bash "$@"
}

case "$cmd" in
    setup) setup ;;
    packages) build_packages ;;
    run)
        [ "$nobuild" = 1 ] || build_packages
        echo "starting the installer (sway, nested in a window); log: probe-logs/dev-run.log"
        # The same session as the ISO: sway (nested in a window here) and squeekboard, the on-screen keyboard.
        # shellcheck disable=SC2016  # expanded inside the container
        in_container -- sh -c 'dbus-uuidgen --ensure=/etc/machine-id 2>/dev/null
            rm -rf "$HOME/.local/share/squeekboard"   # a layout copy from an earlier dev run would override the built-in one
            mkdir -p "$HOME/.config/glib-2.0/settings"
            printf "[sm/puri/Squeekboard]\nscale-in-horizontal-screen-orientation=0.7\n" >"$HOME/.config/glib-2.0/settings/keyfile"
            # sway carries a file capability (cap_sys_nice) that a rootless container cannot grant: a copy has none.
            cp /usr/bin/sway /tmp/sway-nocap
            exec dbus-run-session -- /tmp/sway-nocap -c /etc/boppos-installer/sway.conf' 2>&1 | tee "$repo/probe-logs/dev-run.log"
        ;;
    shell)
        ensure_image
        in_container -it -- bash
        ;;
    *) echo "usage: $0 {run|packages|shell|setup} [--nocheck|--nobuild]"; exit 2 ;;
esac
